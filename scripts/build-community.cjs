// scripts/build-community.cjs
//
// Academy P0.5 · compile the portal's JSX ahead of time.
//
// The community portal used to ship its .jsx files raw and compile them
// in the visitor's browser with @babel/standalone. That cost a 2.8 MB
// download before the first paint, and — because Babel evaluates the
// compiled source — it forced 'unsafe-eval' into the site-wide CSP,
// which is the one directive that makes an injected script dangerous.
//
// This script compiles every public/**/*.jsx to a sibling .js with
// esbuild (already present via Vite). Output is a build artifact:
// .gitignored, regenerated by `npm run build`, and served on the fly in
// dev by the compileJsx middleware in vite.config.ts.
//
// The files are NOT modules — they share globals (SporeData, MycoAgent,
// React) and depend on <script> order in the HTML. So each file is
// transformed in isolation, never bundled: same semantics, same order,
// just no browser-side compile step.
//
//   node scripts/build-community.cjs

const fs      = require('fs');
const path    = require('path');
const esbuild = require('esbuild');

const ROOT = path.resolve(__dirname, '..');
const DIR  = path.join(ROOT, 'public', 'community');

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith('.jsx')) out.push(full);
  }
  return out;
}

// Every portal file starts with `const { useState, … } = React;`. As
// classic scripts sharing one global scope, two files declaring the same
// const is a SyntaxError that kills the whole page. @babel/standalone
// never hit it because it downlevelled const to var, where redeclaration
// is legal. Reproduce exactly that, for exactly that line — nothing else
// about scoping changes.
function varifyReactHooks(source) {
  return source.replace(/^const (\{[^}]*\})\s*=\s*React;/m, 'var $1 = React;');
}

/** Transform one .jsx source string to browser-ready JS. */
function compileSource(source, sourcefile) {
  return esbuild.transformSync(varifyReactHooks(source), {
    loader:      'jsx',
    // NO `format` — an iife/esm wrapper would hide each file's top-level
    // declarations from the next script. These are classic scripts whose
    // top-level functions and consts must stay on the global scope.
    target:      'es2019',      // Safari 13+ / any browser that runs the portal today
    jsx:         'transform',
    jsxFactory:  'React.createElement',
    jsxFragment: 'React.Fragment',
    sourcefile,
    legalComments: 'none',
  }).code;
}

function main() {
  if (!fs.existsSync(DIR)) {
    console.error('public/community not found');
    process.exit(1);
  }
  vendorCobe();
  vendorReact();
  const files = walk(DIR);
  let bytesIn = 0, bytesOut = 0;

  for (const file of files) {
    const src = fs.readFileSync(file, 'utf8');
    let code;
    try {
      code = compileSource(src, path.relative(ROOT, file));
    } catch (err) {
      console.error('  ✗ ' + path.relative(ROOT, file) + ' — ' + err.message);
      process.exit(1);
    }
    const out = file.replace(/\.jsx$/, '.js');
    const banner = '// GENERATED from ' + path.basename(file) + ' by scripts/build-community.cjs — do not edit.\n';
    fs.writeFileSync(out, banner + code);
    bytesIn  += src.length;
    bytesOut += code.length;
    console.log('  ✓ ' + path.relative(ROOT, out).padEnd(54) + (code.length / 1024).toFixed(0) + ' KB');
  }

  // Guard: the portal's scripts share one global scope, so two top-level
  // const/let/class declarations of the same name anywhere in the loaded
  // set is a page-killing SyntaxError. Catch it here, not in production.
  const clashes = findTopLevelClashes();
  if (clashes.length) {
    console.error('');
    console.error('✗ top-level name collisions across the scripts /community loads:');
    for (const c of clashes) console.error('    ' + c.name + ' — ' + c.files.join(', '));
    console.error('  Rename one, or attach it to window instead.');
    process.exit(1);
  }

  console.log('');
  console.log('compiled : ' + files.length + ' files');
  console.log('in/out   : ' + (bytesIn / 1024).toFixed(0) + ' KB → ' + (bytesOut / 1024).toFixed(0) + ' KB');
}

// The network globe (spore/network-globe.jsx) uses cobe. The portal has no
// bundler, so a local copy of cobe's single-file ESM build lives in
// public/community/vendor/ and index.html loads it as a module. Refresh it
// from node_modules each build so it can never drift from package.json.
function vendorCobe() {
  const src = path.join(ROOT, 'node_modules', 'cobe', 'dist', 'index.esm.js');
  if (!fs.existsSync(src)) { console.error('✗ cobe not installed — run npm install'); process.exit(1); }
  const version = require(path.join(ROOT, 'node_modules', 'cobe', 'package.json')).version;
  const out = path.join(DIR, 'vendor', 'cobe.esm.js');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const header = '/*! cobe ' + version + ' · MIT · https://github.com/shuding/cobe\n'
    + '   Local copy for the Spore portal, refreshed from node_modules by\n'
    + '   scripts/build-community.cjs — do not edit by hand. */\n';
  fs.writeFileSync(out, header + fs.readFileSync(src, 'utf8'));
  console.log('  ✓ ' + path.relative(ROOT, out).padEnd(54) + 'cobe ' + version);
}

// React itself. The portal loaded react.development.js + react-dom.development.js
// from unpkg — 1,162 KB of unminified React, running every dev-only warning and
// validation path on a member's first paint. The production UMDs are 139 KB and
// are the same API. Vendored for the same reasons as cobe: nothing third-party
// on the critical path, and it cannot drift from package.json.
function vendorReact() {
  for (const pkg of ['react', 'react-dom']) {
    const src = path.join(ROOT, 'node_modules', pkg, 'umd', pkg + '.production.min.js');
    if (!fs.existsSync(src)) { console.error('✗ ' + pkg + ' not installed — run npm install'); process.exit(1); }
    const version = require(path.join(ROOT, 'node_modules', pkg, 'package.json')).version;
    const out = path.join(DIR, 'vendor', pkg + '.production.min.js');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const header = '/*! ' + pkg + ' ' + version + ' · MIT · https://react.dev\n'
      + '   Local copy for the Spore portal, refreshed from node_modules by\n'
      + '   scripts/build-community.cjs — do not edit by hand. */\n';
    fs.writeFileSync(out, header + fs.readFileSync(src, 'utf8'));
    console.log('  ✓ ' + path.relative(ROOT, out).padEnd(54) + pkg + ' ' + version);
  }
}

// Scripts the portal actually loads, in order, read from the HTML so the
// guard tracks reality rather than a hardcoded list.
function loadedScripts() {
  const html = fs.readFileSync(path.join(DIR, 'index.html'), 'utf8');
  const out = [];
  const re = /<script[^>]*src="([^"]+\.js)"/g;
  let m;
  while ((m = re.exec(html))) {
    if (/^https?:/.test(m[1])) continue;
    const rel = m[1].replace(/^\//, '');
    const jsx = path.join(m[1].startsWith('/') ? path.join(ROOT, 'public') : DIR, rel).replace(/\.js$/, '.jsx');
    if (fs.existsSync(jsx)) out.push(jsx);
  }
  return out;
}

function findTopLevelClashes() {
  const seen = new Map();   // name -> [file, …]
  const re = /^(?:const|let|class)\s+(?:\{([^}]*)\}|([A-Za-z_$][\w$]*))/gm;
  for (const file of loadedScripts()) {
    // varifyReactHooks turns the shared React line into `var`, which may
    // legally repeat — analyse the same text the browser will run.
    const src = varifyReactHooks(fs.readFileSync(file, 'utf8'));
    const names = new Set();
    let m;
    while ((m = re.exec(src))) {
      const group = m[1]
        ? m[1].split(',').map(n => n.split(':').pop().trim()).filter(Boolean)
        : [m[2]];
      for (const n of group) names.add(n);
    }
    for (const n of names) {
      if (!seen.has(n)) seen.set(n, []);
      seen.get(n).push(path.basename(file));
    }
  }
  return [...seen.entries()]
    .filter(([, files]) => files.length > 1)
    .map(([name, files]) => ({ name, files }));
}

if (require.main === module) main();
module.exports = { compileSource };
